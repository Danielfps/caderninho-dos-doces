create table if not exists public.contratacoes (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  plano text not null check (plano in ('mensal', 'anual')),
  valor_inicial numeric(10,2) not null check (valor_inicial > 0),
  valor_recorrente numeric(10,2) not null check (valor_recorrente > 0),
  moeda text not null default 'BRL' check (moeda = 'BRL'),
  estado text not null check (estado in ('checkout_pendente','aguardando_pagamento','ativa','pausada','falha_pagamento','cancelada','encerrada','abandonada')),
  mp_plano_id text unique,
  mp_preapproval_id text unique,
  mp_status text,
  mp_atualizado_em timestamptz,
  init_point text,
  proxima_cobranca timestamptz,
  autorizada_em timestamptz,
  cancelada_em timestamptz,
  sincronizada_em timestamptz,
  expira_em timestamptz not null default (now() + interval '24 hours'),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create unique index if not exists contratacoes_uma_viva_por_usuario
  on public.contratacoes(user_id)
  where user_id is not null and estado in ('checkout_pendente','aguardando_pagamento','ativa','pausada','falha_pagamento');
create index if not exists contratacoes_reconciliar_idx
  on public.contratacoes(sincronizada_em, proxima_cobranca)
  where estado in ('checkout_pendente','aguardando_pagamento','ativa','pausada','falha_pagamento');

create table if not exists public.cobrancas (
  mp_cobranca_id text primary key,
  contratacao_id uuid not null references public.contratacoes(id) on delete restrict,
  user_id uuid references auth.users(id) on delete set null,
  mp_pagamento_id text,
  valor numeric(10,2) not null check (valor >= 0),
  estado text not null check (estado in ('pendente','aprovada','recusada','estornada')),
  mp_status text not null,
  mp_pagamento_status text,
  debitada_em timestamptz,
  valido_de timestamptz,
  valido_ate timestamptz,
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists cobrancas_usuario_validade_idx
  on public.cobrancas(user_id, valido_ate desc) where estado = 'aprovada';
create index if not exists cobrancas_contratacao_data_idx
  on public.cobrancas(contratacao_id, debitada_em desc, criado_em desc);

create table if not exists public.eventos_pagamento (
  id bigint generated by default as identity primary key,
  chave text not null unique,
  tipo text not null,
  acao text not null,
  mp_id text,
  ao_vivo boolean not null default false,
  recebido_em timestamptz not null default now(),
  repeticoes integer not null default 1,
  resultado text not null default 'recebido' check (resultado in ('recebido','ok','ignorado','erro')),
